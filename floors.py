def kind_of(name):
    """방 이름으로 종류를 정한다 (색칠용)"""
    if any(k in name for k in ("화장실", "샤워", "세면", "탈의")):
        return "toilet"
    if "계단" in name:
        return "stair"
    if any(k in name for k in ("복도", "홀", "통로", "마당", "연결")):
        return "hall"
    if "빈 공간" in name:
        return "void"
    if any(k in name for k in ("휴게", "관람석", "매점", "식당")):
        return "rest"
    if any(k in name for k in ("교무", "교감", "교장", "행정", "연구실", "부속", "탕비", "이사장", "창고", "준비실",
                               "기계실", "보일러", "문서고", "영양사", "사감", "제한", "방송", "전산", "인쇄",
                               "회의", "안내", "지도자", "비품", "분석", "부장", "관찰", "학부모", "다용도",
                               "주방", "전처리", "방")):
        return "office"
    return "class"
