#   "rot90"  도면 오른쪽 = 북쪽, 도면 위 = 서쪽


def row(names, x_edges, y0, y1):
    """한 줄로 늘어선 방들"""
    return [(n, x_edges[i], x_edges[i + 1], y0, y1) for i, n in enumerate(names)]


